#!/usr/bin/env python3
"""
CalSol Memory Bloat & Size Reporter
Parses ESP-IDF size JSON output, analyzes SRAM (DRAM/IRAM) and Flash utilization,
and injects a formatted Markdown table into GITHUB_STEP_SUMMARY.
"""

import os
import sys
import json
import argparse

if hasattr(sys.stdout, "reconfigure"):
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

def format_bytes(b):
    if b < 1024:
        return f"{b} B"
    elif b < 1024 * 1024:
        return f"{b / 1024:.1f} KB"
    else:
        return f"{b / (1024 * 1024):.2f} MB"

def parse_size_json(size_file):
    with open(size_file, "r", encoding="utf-8") as f:
        data = json.load(f)

    layout = data.get("layout", [])
    memory = {}

    for item in layout:
        name = item.get("name")
        used = item.get("used", 0)
        total = item.get("total", 0)
        free = item.get("free", 0)
        memory[name] = {
            "used": used,
            "total": total,
            "free": free,
            "parts": item.get("parts", {})
        }

    return memory, data.get("total_size", 0)

def evaluate_memory(memory, total_size, subsystem_name):
    # DRAM
    dram = memory.get("DRAM", {"used": 0, "total": 0})
    dram_used = dram["used"]
    dram_total = dram["total"]
    dram_pct = (dram_used / dram_total * 100.0) if dram_total > 0 else 0.0

    # IRAM
    iram = memory.get("IRAM", {"used": 0, "total": 0})
    iram_used = iram["used"]
    iram_total = iram["total"]
    iram_pct = (iram_used / iram_total * 100.0) if iram_total > 0 else 0.0

    # Flash Code + Data
    flash_code = memory.get("Flash Code", {"used": 0})["used"]
    flash_data = memory.get("Flash Data", {"used": 0})["used"]
    flash_used = flash_code + flash_data
    # Typical 1MB app partition limit (0x100000 bytes) as reference
    flash_limit = 1024 * 1024
    flash_pct = (flash_used / flash_limit * 100.0)

    # Status
    if dram_pct >= 90.0 or flash_pct >= 90.0:
        overall_status = "CRITICAL"
        badge = "🔴 Critical"
    elif dram_pct >= 75.0 or flash_pct >= 75.0:
        overall_status = "WARNING"
        badge = "🟡 Warning"
    else:
        overall_status = "OK"
        badge = "🟢 Safe"

    summary_data = {
        "subsystem": subsystem_name,
        "overall_status": overall_status,
        "dram_used": dram_used,
        "dram_total": dram_total,
        "dram_pct": round(dram_pct, 1),
        "iram_used": iram_used,
        "iram_total": iram_total,
        "iram_pct": round(iram_pct, 1),
        "flash_used": flash_used,
        "flash_limit": flash_limit,
        "flash_pct": round(flash_pct, 1),
        "total_binary_size": total_size
    }

    markdown = []
    markdown.append(f"### 📊 Memory Footprint: `{subsystem_name}` ({badge})\n")
    markdown.append("| Memory Region | Used | Capacity / Limit | Utilization | Status |")
    markdown.append("| :--- | :---: | :---: | :---: | :---: |")

    # DRAM row
    dram_stat = "🟢 OK" if dram_pct < 75 else ("🟡 High" if dram_pct < 90 else "🔴 Low Memory")
    markdown.append(f"| **DRAM (Data / BSS RAM)** | `{format_bytes(dram_used)}` | `{format_bytes(dram_total)}` | `{dram_pct:.1f}%` | {dram_stat} |")

    # IRAM row
    iram_stat = "🟢 OK" if iram_pct < 75 else ("🟡 High" if iram_pct < 90 else "🔴 Critical")
    markdown.append(f"| **IRAM (Instruction RAM)** | `{format_bytes(iram_used)}` | `{format_bytes(iram_total)}` | `{iram_pct:.1f}%` | {iram_stat} |")

    # Flash row
    flash_stat = "🟢 OK" if flash_pct < 75 else ("🟡 High" if flash_pct < 90 else "🔴 Partition Near Full")
    markdown.append(f"| **Flash (Code + Data)** | `{format_bytes(flash_used)}` | `{format_bytes(flash_limit)}` | `{flash_pct:.1f}%` | {flash_stat} |")
    markdown.append("")

    return summary_data, "\n".join(markdown)

def main():
    parser = argparse.ArgumentParser(description="CalSol Memory Bloat & Size Reporter")
    parser.add_argument("--size-file", required=True, help="Path to size_info.json generated by idf.py size --format json2")
    parser.add_argument("--subsystem", required=True, help="Subsystem name (e.g. pedals_fw)")
    parser.add_argument("--output-json", help="Path to write summary JSON")
    args = parser.parse_args()

    if not os.path.exists(args.size_file):
        print(f"[-] Size file {args.size_file} does not exist.")
        sys.exit(1)

    try:
        memory, total_size = parse_size_json(args.size_file)
        summary_data, md_table = evaluate_memory(memory, total_size, args.subsystem)

        print(md_table)

        # Write to GITHUB_STEP_SUMMARY if available
        summary_file = os.environ.get("GITHUB_STEP_SUMMARY")
        if summary_file:
            with open(summary_file, "a", encoding="utf-8") as f:
                f.write(md_table + "\n")

        # Write output JSON if requested
        if args.output_json:
            os.makedirs(os.path.dirname(os.path.abspath(args.output_json)), exist_ok=True)
            with open(args.output_json, "w", encoding="utf-8") as f:
                json.dump(summary_data, f, indent=2)
            print(f"[+] Memory summary JSON saved to {args.output_json}")

    except Exception as e:
        print(f"[-] Failed to process size file: {e}")
        sys.exit(1)

if __name__ == "__main__":
    main()
